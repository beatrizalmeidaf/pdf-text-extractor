def _drop_caps(chars: list[Char]) -> list[Char]:
    """A drop cap (a big "T" spanning the first lines of a paragraph) would fuse the lines
    beside it into one. Put it on its first line, right before the word it starts."""
    if len(chars) < 20:
        return chars
    typical = statistics.median(c.size for c in chars)
    out = chars
    for i, c in enumerate(chars[:-1]):
        if c.size < typical * 2.2 or not c.c.isalpha():
            continue
        n = chars[i + 1]
        if (
            n.size > typical * 1.5
            or not c.y0 <= n.cy <= c.y1
            or not -1 <= n.x0 - c.x1 <= typical * 1.5
        ):
            continue
        beside = any(
            o.size <= typical * 1.5
            and n.y1 < o.cy < c.y1
            and c.x1 - 1 <= o.x0 <= c.x1 + typical * 1.5
            for o in chars[i + 2 : i + 600]
        )
        if beside:
            out = list(out) if out is chars else out
            w = n.size * 0.7
            out[i] = Char(c.c, n.x0 - w - 0.1, n.y0, n.x0 - 0.1, n.y1, c.font, c.space, c.newline)
    return out


def build_spans(
    chars: list[Char], fonts: list[FontInfo], gutters_out: list | None = None
) -> list[Span]:
    """Group chars into visual lines (stream order + geometry), then split at wide gaps."""
    chars = _drop_caps(chars)
    raw_lines: list[list[Char]] = []
    cur: list[Char] = []
    for ch in chars:
        if cur:
            last = cur[-1]
            overlap = min(last.y1, ch.y1) - max(last.y0, ch.y0)
            small = min(last.size, ch.size)
            same_line = overlap >= small * 0.35 and ch.x0 >= last.x0 - small * 0.5
            if not same_line or (ch.newline and not overlap >= small * 0.8):
                raw_lines.append(cur)
                cur = []
        cur.append(ch)
    if cur:
        raw_lines.append(cur)

    raw_lines = _merge_fragments(raw_lines)
    # The page's column gutters, from its runs of words: a gap that swallows a whole gutter
    # joins two columns (an equation number drawn right before the next column's line).
    runs = []
    for line in raw_lines:
        size = max(statistics.median(c.size for c in line), 4)
        start = 0
        for i in range(1, len(line) + 1):
            if i < len(line) and line[i].x0 - line[i - 1].x1 <= size * 0.5:
                continue
            run = line[start:i]
            runs.append(
                (run[0].x0, min(c.y0 for c in run), max(c.x1 for c in run), max(c.y1 for c in run))
            )
            start = i
    gaps = page_gutters(runs)
    if gutters_out is not None:
        gutters_out.extend(gaps)
    spans: list[Span] = []
    for line in raw_lines:
        line = _compose_accents(line)
        size = max(statistics.median(c.size for c in line), 4)
        # Justified lines stretch every word gap by about the same amount, so a gap only
        # separates columns/cells when it is much wider than this line's usual word gap.
        pairs = list(zip(line, line[1:], strict=False))
        word_gaps = [b.x0 - a.x1 for a, b in pairs if b.space or b.x0 - a.x1 > size * WORD_GAP_EM]
        typical = statistics.median(word_gaps) if len(word_gaps) >= 3 else 0.0
        # The line sets its word gaps with real space glyphs: a gap this wide without one is
        # a jump of the pen — an equation number followed by the next column's line.
        spaced = sum(c.space == 2 for c in line) >= 3
        piece = [line[0]]
        for prev, ch in pairs:
            gap = ch.x0 - prev.x1
            wide = gap > size * SPAN_GAP_EM and (
                gap > typical * 2.2 or gap > size * JUSTIFIED_GAP_EM
            )
            if ch.space == 2 and gap < size * JUSTIFIED_GAP_EM:
                wide = False  # a real space char means "same text run"
            if spaced and ch.space != 2 and gap > size * SPAN_GAP_EM:
                wide = True
            if any(prev.x1 <= g0 + 2.5 and ch.x0 >= g1 - 2.5 for g0, g1 in gaps):
                wide = True
            if wide:
                spans.append(Span(piece, fonts))
                piece = []
            piece.append(ch)
        spans.append(Span(piece, fonts))
    return _join_markers(spans, gaps)


def _compose_accents(line: list[Char]) -> list[Char]:
    """Merge accents drawn as separate glyphs into their letter ('a' + '˜' -> 'ã').

    The letter is the neighbour the accent overlaps horizontally; without overlap, accents
    drawn above attach to the previous letter and cedillas/ogoneks to the next one.
    """
    if not any(c.c in SPACING_ACCENTS for c in line):
        return line
    out = list(line)
    i = 0
    while i < len(out):
        acc = out[i]
        if acc.c not in SPACING_ACCENTS:
            i += 1
            continue
        best, best_score = None, 0.0
        for j in (i - 1, i + 1):
            if not 0 <= j < len(out) or compose_accent(out[j].c, acc.c) is None:
                continue
            base = out[j]
            overlap = min(base.x1, acc.x1 + 0.5) - max(base.x0, acc.x0 - 0.5)
            near = max(base.x0 - acc.x1, acc.x0 - base.x1) < max(acc.size, 4) * 0.3
            prefer = (j > i) == (SPACING_ACCENTS[acc.c] in BELOW_ACCENTS)
            score = overlap if overlap > 0 else (0.5 if near and prefer else 0.0)
            if score > best_score:
                best, best_score = j, score
        if best is None:
            i += 1
            continue
        base = out[best]
        base.c = compose_accent(base.c, acc.c)
        base.space = max(base.space, acc.space) if best > i else base.space
        del out[i]
        # Drawing the accent moves the pen back: a fake space can follow the composed letter.
        k = out.index(base) + 1
        if k < len(out) and out[k].x0 - base.x1 < max(out[k].size, 4) * 0.15:
            out[k].space = 0
    return out


def _order_line(fragments: list[list[Char]]) -> list[Char]:
    """Glyphs of one visual line, left to right. A limit set under or over an operator
    ("max" with its subscript below) overlaps it sideways: it goes right after the glyphs
    it is stacked on, as one piece, instead of being shuffled into them."""
    if len(fragments) == 1:
        return sorted(fragments[0], key=lambda c: c.x0)
    sizes = [statistics.median(c.size for c in f) for f in fragments]
    main = max(sizes)
    base = [c for f, s in zip(fragments, sizes, strict=True) if s > main * 0.85 for c in f]
    keyed: list[tuple[tuple[float, int, float], Char]] = []
    for f, s in zip(fragments, sizes, strict=True):
        anchor = None
        if s <= main * 0.85 and base:
            x0, x1 = min(c.x0 for c in f), max(c.x1 for c in f)
            y0, y1 = min(c.y0 for c in f), max(c.y1 for c in f)
            stacked = [
                c
                for c in base
                if x0 <= c.cx <= x1 and min(c.y1, y1) - max(c.y0, y0) < (y1 - y0) * 0.3
            ]
            if stacked:
                anchor = max(c.x1 for c in stacked) - 0.01
        keyed += [((c.x0, 0, 0.0) if anchor is None else (anchor, 1, c.x0), c) for c in f]
    keyed.sort(key=lambda t: t[0])
    return [c for _, c in keyed]


def _merge_fragments(lines: list[list[Char]]) -> list[list[Char]]:
    """Fragments of one visual line drawn at different moments of the stream."""
    if len(lines) < 2:
        return [_order_line([ln]) for ln in lines]
    boxes = [
        [min(c.x0 for c in ln), min(c.y0 for c in ln), max(c.x1 for c in ln), max(c.y1 for c in ln)]
        for ln in lines
    ]
    sizes = [statistics.median(c.size for c in ln) for ln in lines]
    # Where the text of each fragment sits, whatever tall glyph (a big operator, a limit)
    # stretches its box: two lines of a formula-heavy paragraph have overlapping boxes.
    mids = [statistics.median(c.cy for c in ln) for ln in lines]
    # A merged line is measured by its main fragment (the text), not by the exponent that
    # happened to be drawn first.
    counts = [len(ln) for ln in lines]
    main_len = list(counts)

    def by_place(i: int) -> tuple[float, float]:
        return boxes[i][1], boxes[i][0]

    # The lines of text first; then each short piece (an exponent, an index, a limit) joins
    # the line it overlaps most, whichever was drawn first. Between two tight lines, the
    # index of the upper one and the exponent of the lower one sit at the same height.
    # (Short pieces set at the text size — "·K", ")" — go before the raised or lowered
    # ones, so that an exponent finds the letter it belongs to already in place.)
    everything = range(len(lines))
    order = sorted((i for i in everything if counts[i] > 6), key=by_place)
    typical = statistics.median(sizes[i] for i in order) if order else statistics.median(sizes)
    plain = {i for i in everything if counts[i] <= 6 and sizes[i] >= typical * 0.95}
    order += sorted(plain, key=by_place)
    order += sorted((i for i in everything if counts[i] <= 6 and i not in plain), key=by_place)
    merged: list[int] = []
    out: dict[int, list[list[Char]]] = {}
    for i in order:
        bi = boxes[i]
        short = len(lines[i]) <= 6
        target, best = None, -math.inf
        for j in merged if short else merged[-6:]:
            bj = boxes[j]
            hi, hj = bi[3] - bi[1], bj[3] - bj[1]
            h = min(hi, hj)
            overlap = min(bi[3], bj[3]) - max(bi[1], bj[1])
            if overlap <= 0:
                continue
            touching = bi[0] <= bj[2] + h * SPAN_GAP_EM and bj[0] <= bi[2] + h * SPAN_GAP_EM
            level = abs(mids[i] - mids[j]) <= min(sizes[i], sizes[j]) * 0.35
            if overlap >= h * 0.7 and touching and level:
                if not short:
                    target = j
                    break
                if overlap / h + 1 > best:
                    target, best = j, overlap / h + 1
                continue
            # A superscript/subscript drawn on its own: smaller glyphs (or a short piece),
            # partly overlapping, glued to the bigger fragment. Two full lines of the same
            # text, one of them taller because of its own scripts, are not that.
            small = i if hi <= hj else j
            big = j if small == i else i  # the script is the piece both shorter and set smaller
            script = sizes[small] <= sizes[big] * 0.85 or counts[small] <= 6
            lone = counts[small] <= 6 and overlap >= h * 0.35  # an exponent placed on its own
            if i in plain or not (
                (h <= max(hi, hj) * 0.8 or lone) and overlap >= h * 0.2 and script
            ):
                continue
            if not short:
                if bi[0] <= bj[2] + h * 0.4 and bj[0] <= bi[2] + h * 0.4:
                    target = j
                    break
                continue
            # Glued to a glyph of that line, not just somewhere along it.
            glyphs = [c for frag in out[j] for c in frag]
            near = any(max(c.x0 - bi[2], bi[0] - c.x1, 0) <= h * 0.5 for c in glyphs)
            # An exponent sits in a gap of its own line; over the other line it hangs above
            # (or below) that line's letters.
            reach = max(0.8, (bi[2] - bi[0]) * 0.12)
            clash = any(min(c.x1, bi[2]) - max(c.x0, bi[0]) > reach for c in glyphs)
            score = overlap / h - (1 if clash else 0)
            if near and score > best:
                target, best = j, score
        if target is None:
            merged.append(i)
            out[i] = [lines[i]]
        else:
            out[target].append(lines[i])
            counts[target] += len(lines[i])
            bigger = sizes[i] > sizes[target] * 1.05
            longer = sizes[i] >= sizes[target] * 0.98 and len(lines[i]) > main_len[target]
            if bigger or longer:
                sizes[target], mids[target], main_len[target] = sizes[i], mids[i], len(lines[i])
            bj = boxes[target]
            boxes[target] = [
                min(bj[0], bi[0]),
                min(bj[1], bi[1]),
                max(bj[2], bi[2]),
                max(bj[3], bi[3]),
            ]
    # A line cut into pieces by its own indices ("H", "2", "O", "2(aq)", "+ I"…): pieces on
    # one baseline that now touch, with their indices attached, are that line.
    merged.sort(key=by_place)
    k = 0
    while k < len(merged):
        a = merged[k]
        for b in merged[k + 1 :]:
            size = min(sizes[a], sizes[b])
            ba, bb = boxes[a], boxes[b]
            if (
                abs(mids[a] - mids[b]) <= size * 0.2
                and abs(sizes[a] - sizes[b]) <= size * 0.15
                and max(bb[0] - ba[2], ba[0] - bb[2]) <= size * 0.9
            ):
                out[a] += out.pop(b)
                boxes[a] = [
                    min(ba[0], bb[0]),
                    min(ba[1], bb[1]),
                    max(ba[2], bb[2]),
                    max(ba[3], bb[3]),
                ]
                merged.remove(b)
                break
        else:
            k += 1
    return [_order_line(out[i]) for i in merged]


def _is_marker(text: str) -> bool:
    t = text.strip()
    return (len(t) == 1 and t in BULLETS) or bool(_ENUM.fullmatch(t))


def _join_markers(spans: list[Span], gaps=()) -> list[Span]:
    """'•' or '1.' followed by the item text (hanging indent) is one span, not two columns.
    (An equation number at the end of a column is not the marker of the next column's line.)"""
    out: list[Span] = []
    left = min((s.x0 for s in spans), default=0.0)
    i = 0
    while i < len(spans):
        s = spans[i]
        if i + 1 < len(spans) and _is_marker(s.text):
            nxt = spans[i + 1]
            same_row = min(s.y1, nxt.y1) - max(s.y0, nxt.y0) > min(s.height, nxt.height) * 0.4
            # (A gutter has a column of text on its left; the gap after "a)" has only "a)".)
            over_gutter = any(
                s.x1 <= g0 + 2.5 and nxt.x0 >= g1 - 2.5 and g0 - left >= 100 for g0, g1 in gaps
            )
            if same_row and not over_gutter and 0 <= nxt.x0 - s.x1 < max(s.size, 6) * 4:
                nxt.chars[0].space = 2
                out.append(Span(s.chars + nxt.chars, s.fonts))
                i += 2
                continue
        out.append(s)
        i += 1
    return out


# ============================================================================ atoms, reading order
@dataclass
class Atom:
    kind: str  # "span" | "table" | "figure"
    x0: float
    y0: float
    x1: float
    y1: float
    span: Span | None = None
    block: Block | None = None

    @property
    def core(self) -> tuple[float, float]:
        if self.kind != "span":
            return self.y0, self.y1
        pad = (self.y1 - self.y0) * 0.22
        return self.y0 + pad, self.y1 - pad


def _bands(items: list[Atom]) -> list[list[Atom]]:
    items = sorted(items, key=lambda a: a.core[0])
    bands: list[list[Atom]] = []
    bottom = -math.inf
    for a in items:
        top, bot = a.core
        if bands and top < bottom:
            bands[-1].append(a)
            bottom = max(bottom, bot)
        else:
            bands.append([a])
            bottom = bot
    return bands


def _gutters(items: list[Atom], min_gap: float) -> list[tuple[float, float]]:
    spans = sorted((a.x0, a.x1) for a in items)
    gaps = []
    end = spans[0][1]
    for x0, x1 in spans[1:]:
        if x0 - end >= min_gap:
            gaps.append((end, x0))
        end = max(end, x1)
    return gaps


def _text_like(side: list[Atom]) -> bool:
    if any(a.kind != "span" for a in side):
        return True
    lengths = [len(a.span.text) for a in side if a.span]
    return bool(lengths) and statistics.median(lengths) >= TEXT_LIKE_CHARS


def _split_columns(items: list[Atom], min_gap: float, page_gaps=()) -> list[list[Atom]] | None:
    if len(items) < 2:
        return None
    cols: list[list[Atom]] = []
    rest = items
    gutters = _gutters(items, min_gap)
    rows = [_table_row(b) and b for b in _bands(items)] if gutters else []
    for g0, g1 in gutters:
        left = [a for a in rest if a.x1 <= g0 + 0.01]
        right = [a for a in rest if a.x0 >= g1 - 0.01]
        # A table has its rows one after the other. One row of short pieces over the gutter
        # (an equation beside a short line of the other column) is not a table.
        across = [
            bool(row)
            and any(a.x1 <= g0 + 0.01 for a in row)
            and any(a.x0 >= g1 - 0.01 for a in row)
            for row in rows
        ]
        run = longest = 0
        for hit in across:
            run = run + 1 if hit else 0
            longest = max(longest, run)
        cuts_table = longest >= 3 or (bool(across) and all(across))
        # The page's own gutter splits even when one side is not prose (labels of a chart).
        # (Never through the rows of a table, however few.)
        known = (
            (_text_like(left) or _text_like(right))
            and not any(across)
            and any(min(b, g1) - max(a, g0) >= (b - a) * 0.5 for a, b in page_gaps)
        )
        prose = _text_like(left) and _text_like(right)
        if left and right and not cuts_table and (known or prose):
            cols.append(left)
            rest = right
    if not cols:
        return None
    cols.append(rest)
    return cols


def _table_row(band: list[Atom]) -> bool:
    """Several short cells side by side (a table row), rather than lines of prose columns."""
    spans = [a.span for a in band if a.kind == "span" and a.span]
    return (
        len(spans) >= 3
        and len(spans) == len(band)
        and all(len(s.text) < TEXT_LIKE_CHARS for s in spans)
    )


def reading_order(items: list[Atom], min_gap: float, page_gaps=()) -> list[list[Atom]]:
    """Column-aware recursive XY-cut. Returns bands (atoms on one visual row) in order."""
    if not items:
        return []
    if len(items) == 1:
        return [items]
    cols = _split_columns(items, min_gap, page_gaps)
    if cols:
        return [band for col in cols for band in reading_order(col, min_gap, page_gaps)]
    bands = _bands(items)
    if len(bands) == 1:
        return [sorted(items, key=lambda a: a.x0)]
    groups: list[list[Atom]] = [bands[0]]
    for k, band in enumerate(bands[1:], start=1):
        union = groups[-1] + band
        # Look two bands ahead: a short heading on top of a column ("Abstract") only proves
        # to be a column once the lines under it are in.
        ahead = [a for b in bands[k + 1 : k + 3] for a in b]
        if _table_row(band) and not _table_row(groups[-1][-1:]):
            groups.append(band)  # a table starts under the columns: don't let a gutter cut it
        elif _split_columns(union, min_gap, page_gaps) or (
            ahead and _split_columns(union + ahead, min_gap, page_gaps)
        ):
            groups[-1] = union
        else:
            groups.append(band)
    out: list[list[Atom]] = []
    for group in groups:
        if len(group) == len(items):  # no progress possible: stop here
            out += [sorted(b, key=lambda a: a.x0) for b in _bands(group)]
        else:
            out += reading_order(group, min_gap, page_gaps)
    return out


# ============================================================================= tables
def _cluster(values: list[float], tol: float) -> list[float]:
    out: list[list[float]] = []
    for v in sorted(values):
        if out and v - out[-1][-1] <= tol:
            out[-1].append(v)
        else:
            out.append([v])
    return [sum(c) / len(c) for c in out]


def _merge_rules(rules: list[tuple[float, float, float]]) -> list[list[float]]:
    rules = sorted(rules)
    out: list[list[float]] = []
    for pos, a, b in rules:
        for r in out[-8:]:
            if abs(r[0] - pos) <= 1.5 and a <= r[2] + 2 and b >= r[1] - 2:
                r[1], r[2] = min(r[1], a), max(r[2], b)
                break
        else:
            out.append([pos, a, b])
    return out


def _prose_between(spans, x0: float, x1: float, ya: float, yb: float) -> bool:
    """Is there running text (not table rows) between two horizontal rules?"""
    for s in spans:
        cx, cy = (s.x0 + s.x1) / 2, (s.y0 + s.y1) / 2
        if x0 <= cx <= x1 and ya < cy < yb:
            words = [w for w in s.text.split() if len(w) >= 2 and w[0].isalpha()]
            if len(words) >= 7:
                return True
    return False


def ruled_regions(
    g: Graphics, spans=()
) -> list[tuple[tuple[float, float, float, float], list[float], list[float], bool]]:
    """Connected grids of rules -> (bbox, column x's, row y's, has real vertical rules)."""
    H = _merge_rules(g.hrules)
    V = _merge_rules(g.vrules)
    n = len(H) + len(V)
    if len(H) < 2:
        return []
    parent = list(range(n))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    tol = 2.5
    for i, (hy, hx0, hx1) in enumerate(H):
        for j, (vx, vy0, vy1) in enumerate(V):
            if hx0 - tol <= vx <= hx1 + tol and vy0 - tol <= hy <= vy1 + tol:
                parent[find(i)] = find(len(H) + j)
    # Stacked horizontal rules of similar extent with no verticals (booktabs, Word "rows
    # only") — unless running text sits between them: a page-header rule and a table further
    # down share the page width, but the paragraphs in between are not table cells.
    # Rules already tied to vertical rules belong to a full grid: two Word tables of the same
    # width, one below the other, are two tables.
    gridded = {find(len(H) + j) for j in range(len(V))}
    for i in range(len(H)):
        for j in range(i + 1, len(H)):
            a, b = H[i], H[j]
            if find(i) in gridded or find(j) in gridded:
                continue
            if abs(a[1] - b[1]) <= 4 and abs(a[2] - b[2]) <= 4 and a[2] - a[1] > 30:
                lo, hi = sorted((a[0], b[0]))
                image_between = any(im[1] < hi and im[3] > lo for im in g.images)
                if not image_between and not _prose_between(spans, a[1], a[2], lo, hi):
                    parent[find(i)] = find(j)
    comps: dict[int, list[int]] = {}
    for i in range(n):
        comps.setdefault(find(i), []).append(i)
    out = []
    for members in comps.values():
        hs = [H[i] for i in members if i < len(H)]
        vs = [V[i - len(H)] for i in members if i >= len(H)]
        if len(hs) < 2:
            continue
        x0 = min([h[1] for h in hs] + [v[0] for v in vs])
        x1 = max([h[2] for h in hs] + [v[0] for v in vs])
        y0 = min([h[0] for h in hs] + [v[1] for v in vs])
        y1 = max([h[0] for h in hs] + [v[2] for v in vs])
        if x1 - x0 < 30 or y1 - y0 < 8:
            continue
        xs = _cluster([v[0] for v in vs] + [x0, x1], 3)
        ys = _cluster([h[0] for h in hs] + [y0, y1], 2)
        out.append(((x0, y0, x1, y1), xs, ys, len(xs) >= 3))
    return out


def _chars_text(chars: list[Char]) -> str:
    """Multi-line text of a set of chars (cell contents, figure labels)."""
    if not chars:
        return ""
    chars = sorted(chars, key=lambda c: (c.cy, c.x0))
    lines: list[list[Char]] = [[chars[0]]]
    for ch in chars[1:]:
        last = lines[-1]
        ref = statistics.median(c.cy for c in last)
        if abs(ch.cy - ref) <= max(ch.size, last[0].size) * 0.45:
            last.append(ch)
        else:
            lines.append([ch])
    out = []
    for ln in lines:
        ln.sort(key=lambda c: c.x0)
        out.append(segments_text(_segments(ln, _mode_size(ln))))
    return "\n".join(t.strip() for t in out if t.strip())


@dataclass
class Word:
    """A run of glyphs with no space inside: the unit that goes into a table cell, so a
    column boundary can never cut "0,014" or "Brasília" in two."""

    chars: list[Char]

    @property
    def x0(self) -> float:
        return self.chars[0].x0

    @property
    def x1(self) -> float:
        return max(c.x1 for c in self.chars)

    @property
    def cx(self) -> float:
        return (self.x0 + self.x1) / 2

    @property
    def cy(self) -> float:
        return statistics.median(c.cy for c in self.chars)


def words_of(span: Span) -> list[Word]:
    size = max(span.size, 4)
    words: list[Word] = []
    cur = [span.chars[0]]
    for prev, ch in zip(span.chars, span.chars[1:], strict=False):
        gap = ch.x0 - prev.x1
        if ch.space == 2 or gap > size * 0.25 or (ch.space and gap > size * 0.1):
            words.append(Word(cur))
            cur = []
        cur.append(ch)
    words.append(Word(cur))
    return words


def _projection_columns(spans: list[Span], x0: float, x1: float) -> list[float]:
    """Column boundaries: vertical whitespace channels that no word crosses.

    Rows with far fewer words than usual (a title spanning several columns, a
    "Fase 1 - Iniciação" divider) are left out of the projection: they would cover the
    channels of the columns below them.
    """
    atoms = [Atom("span", s.x0, s.y0, s.x1, s.y1, span=s) for s in spans]
    bands = [[w for a in band for w in words_of(a.span)] for band in _bands(atoms)]
    counts = [len(b) for b in bands]
    typical = statistics.median(counts)
    body = [b for b, n in zip(bands, counts, strict=True) if n >= typical * 0.5 and n >= 2]
    words = [w for b in (body if len(body) >= 2 else bands) for w in b]
    size = statistics.median(s.size for s in spans)
    min_gap = max(3.0, size * 0.55)
    ivs = sorted((w.x0, w.x1) for w in words)
    bounds = [x0]
    end = ivs[0][1]
    for a, b in ivs[1:]:
        if a - end >= min_gap:
            bounds.append((a + end) / 2)
        end = max(end, b)
    bounds.append(x1)
    return bounds


def _grid_rows(words: list[Word], xs: list[float], ys: list[float]) -> list[list[str]]:
    ncol, nrow = len(xs) - 1, len(ys) - 1
    cells: list[list[list[Char]]] = [[[] for _ in range(ncol)] for _ in range(nrow)]
    for w in words:
        r = _bucket(w.cy, ys)
        c = _bucket(w.cx, xs)
        if r is not None and c is not None:
            cells[r][c].extend(w.chars)
    rows = [[_chars_text(cell) for cell in row] for row in cells]
    rows = [row for row in rows if any(row)]
    if rows:
        keep = [j for j in range(ncol) if any(row[j] for row in rows)]
        rows = [[row[j] for j in keep] for row in rows]
    return rows


def _bucket(v: float, edges: list[float]) -> int | None:
    if v < edges[0] - 1 or v > edges[-1] + 1:
        return None
    for i in range(len(edges) - 1):
        if v <= edges[i + 1]:
            return i
    return len(edges) - 2


def _table_block(bbox, rows: list[list[str]]) -> Block | None:
    if len(rows) < 2 or max(len(r) for r in rows) < 2:
        return None
    filled = sum(1 for r in rows for c in r if c)
    if filled < 3:
        return None
    text = "\n".join(" | ".join(c.replace("\n", " ") for c in r) for r in rows)
    return Block("table", tuple(bbox), text=text, rows=rows)


def _band_rows(spans: list[Span]) -> list[float]:
    """Row boundaries from text bands (used when rules don't separate rows)."""
    atoms = [Atom("span", s.x0, s.y0, s.x1, s.y1, span=s) for s in spans]
    bands = _bands(atoms)
    edges = [min(a.y0 for a in bands[0])]
    for prev, nxt in zip(bands, bands[1:], strict=False):
        edges.append((max(a.y1 for a in prev) + min(a.y0 for a in nxt)) / 2)
    edges.append(max(a.y1 for a in bands[-1]))
    return edges


def _logical_rows(spans: list[Span], ys: list[float], xs: list[float]) -> list[float]:
    """Row edges for a table whose rules don't separate every row (booktabs, Word "rows only").

    Decided inside each interval between two rules: when the gaps between text lines come
    in two sizes, only the big ones separate rows (cells that wrap are set tighter); a line
    filling far fewer columns than the one above, set tight under it, continues its cells.
    """
    edges = list(ys)
    for a, b in zip(ys, ys[1:], strict=False):
        inside = [s for s in spans if a <= (s.y0 + s.y1) / 2 <= b]
        if len(inside) < 2:
            continue
        bands = _bands([Atom("span", s.x0, s.y0, s.x1, s.y1, span=s) for s in inside])
        if len(bands) < 2:
            continue
        tops = [min(t.y0 for t in band) for band in bands]
        bottoms = [max(t.y1 for t in band) for band in bands]
        gaps = [tops[k + 1] - bottoms[k] for k in range(len(bands) - 1)]
        h = statistics.median(bt - tp for tp, bt in zip(tops, bottoms, strict=True))
        threshold = min(gaps) + max(1.5, h * 0.3)
        bimodal = len(gaps) >= 2 and max(gaps) > threshold
        cols = [len({_bucket((t.x0 + t.x1) / 2, xs) for t in band}) for band in bands]
        for k, gap in enumerate(gaps):
            if bimodal:
                split = gap > threshold
            else:
                continuation = cols[k + 1] < cols[k] * 0.6 and gap < h * 0.6
                split = not continuation
            if split:
                edges.append((bottoms[k] + tops[k + 1]) / 2)
    return sorted(set(_cluster(edges, 2)))


def detect_ruled_tables(spans: list[Span], g: Graphics) -> tuple[list[Block], list[Span]]:
    tables: list[Block] = []
    used: set[int] = set()
    for bbox, xs, ys, real_v in ruled_regions(g, spans):
        x0, y0, x1, y1 = bbox
        inside = [
            i for i, s in enumerate(spans)
            if i not in used
            and x0 - 2 <= (s.x0 + s.x1) / 2 <= x1 + 2
            and y0 - 2 <= (s.y0 + s.y1) / 2 <= y1 + 2
        ]  # fmt: skip
        if not inside:
            continue
        ins = [spans[i] for i in inside]
        if not real_v:  # rows only: take columns from text alignment
            xs = _projection_columns(ins, x0, x1)
        # Rows: trust the rules of a full grid (a cell may wrap over several lines). Split
        # by text bands when rules only frame the table (booktabs: top/mid/bottom), or when
        # a rule row holds several lines with cells in several columns.
        if not real_v:
            ys = _logical_rows(ins, ys, xs)
        words = [w for s in ins for w in words_of(s)]
        block = _table_block(bbox, _grid_rows(words, xs, ys))
        if block is None:
            continue
        tables.append(block)
        used.update(inside)
    return tables, [s for i, s in enumerate(spans) if i not in used]


def _looks_unruled_rows(spans: list[Span], ys: list[float]) -> bool:
    """A rule row holding 3+ text lines that each have 2+ cells is several rows."""
    for a, b in zip(ys, ys[1:], strict=False):
        inside = [s for s in spans if a <= (s.y0 + s.y1) / 2 <= b]
        bands = _bands([Atom("span", s.x0, s.y0, s.x1, s.y1, span=s) for s in inside])
        if len(bands) >= 3 and sum(1 for band in bands if len(band) >= 2) >= 3:
            return True
    return False


def unruled_table(bands: list[list[Atom]], start: int, body: float) -> tuple[Block | None, int]:
    """Try to grow a table from bands[start]; return (table, index after it)."""
    first = bands[start]
    if len(first) < 2 or any(a.kind != "span" for a in first):
        return None, start
    run = [first]
    singles = 0
    j = start + 1
    while j < len(bands):
        band = bands[j]
        if any(a.kind != "span" for a in band):
            break
        prev_bottom = max(a.y1 for a in run[-1])
        top = min(a.y0 for a in band)
        if top - prev_bottom > body * 1.6:
            break
        spans = [a.span for b in run + [band] for a in b]
        rx0 = min(s.x0 for s in spans)
        rx1 = max(s.x1 for s in spans)
        cols = _projection_columns(spans, rx0, rx1)
        if len(cols) < 3:
            break
        if len(band) == 1:
            if band[0].span.width > (rx1 - rx0) * 0.6 or singles >= 1:
                break
            singles += 1
        else:
            if not _distinct_columns(band, cols):
                break
            singles = 0
        run.append(band)
        j += 1
    while run and len(run[-1]) == 1:
        run.pop()
        j -= 1
    multi = [b for b in run if len(b) >= 2]
    spans = [a.span for b in run for a in b]
    if not spans:
        return None, start
    rx0, rx1 = min(s.x0 for s in spans), max(s.x1 for s in spans)
    cols = _projection_columns(spans, rx0, rx1)
    ncols = len(cols) - 1
    if len(multi) < 3 and not (len(multi) >= 2 and ncols >= 3):
        return None, start
    lengths = [len(s.text) for s in spans]
    words = [len(s.text.split()) for s in spans]
    if statistics.median(lengths) > 38 or (ncols <= 3 and statistics.median(words) >= 6):
        return None, start  # prose in columns, not a table
    # Row edges between multi-cell bands; a single-span band continues the row above.
    rows_edges = [min(a.y0 for a in run[0])]
    for prev, band in zip(run, run[1:], strict=False):
        if len(band) >= 2:
            rows_edges.append((max(a.y1 for a in prev) + min(a.y0 for a in band)) / 2)
    rows_edges.append(max(a.y1 for a in run[-1]))
    words = [w for s in spans for w in words_of(s)]
    rows = _grid_rows(words, cols, rows_edges)
    y0 = min(s.y0 for s in spans)
    y1 = max(s.y1 for s in spans)
    return _table_block((rx0, y0, rx1, y1), rows), j


def _distinct_columns(band: list[Atom], cols: list[float]) -> bool:
    seen = set()
    for a in band:
        c = _bucket((a.x0 + a.x1) / 2, cols)
        if c in seen:
            return False
        seen.add(c)
    return True


# ============================================================================= figures
def _plot_frames(g: Graphics, spans) -> list[list[float]]:
    """Rectangles of rules holding many vector marks and little text: the axes of a plot
    whose marks are too sparse to cluster (scatter plots). A table is the opposite."""
    H = _merge_rules(g.hrules)
    V = _merge_rules(g.vrules)
    if len(V) > 200 or len(g.ink) < 8:
        return []
    frames = []
    for i, left in enumerate(V):
        for right in V[i + 1 :]:
            if (
                right[0] - left[0] < 30
                or abs(left[1] - right[1]) > 3
                or abs(left[2] - right[2]) > 3
            ):
                continue
            x0, x1, y0, y1 = left[0], right[0], max(left[1], right[1]), min(left[2], right[2])
            top = any(abs(h[0] - y0) <= 3 and h[1] <= x0 + 3 and h[2] >= x1 - 3 for h in H)
            bottom = any(abs(h[0] - y1) <= 3 and h[1] <= x0 + 3 and h[2] >= x1 - 3 for h in H)
            if not (top and bottom) or y1 - y0 < 30:
                continue
            box = (x0, y0, x1, y1)
            marks = sum(1 for b in g.ink if _inside(b, box, 1))
            texts = sum(1 for s in spans if _inside((s.x0, s.y0, s.x1, s.y1), box, 1))
            if marks >= 8 and marks >= texts * 3:
                frames.append(list(box))
    return frames


def chart_regions(g: Graphics, width: float, height: float, spans=()) -> list[list[float]]:
    """Vector charts: clusters of non-rule ink (data curves, bars, markers) and plot frames
    full of marks, grown to take in the rules drawn around them (axes, ticks, legend)."""
    boxes = [list(b) for b in _cluster_boxes(g.ink, 6) if _area(b) > width * height * 0.01]
    frames = _plot_frames(g, spans)
    if frames:
        boxes = [list(b) for b in _cluster_boxes([tuple(b) for b in boxes + frames], 2)]
    rules = [(x0, y, x1, y) for y, x0, x1 in g.hrules] + [(x, y0, x, y1) for x, y0, y1 in g.vrules]
    for box in boxes:
        for _ in range(4):
            w, h = box[2] - box[0], box[3] - box[1]
            grow = [box[0] - w * 0.25, box[1] - h * 0.25, box[2] + w * 0.25, box[3] + h * 0.25]
            near = [box[0] - 6, box[1] - 6, box[2] + 6, box[3] + 6]
            changed = False
            for r in rules:
                touches = (
                    r[0] <= near[2] and r[2] >= near[0] and r[1] <= near[3] and r[3] >= near[1]
                )
                if touches and _inside(r, grow) and not _inside(r, box):
                    box[0], box[1] = min(box[0], r[0]), min(box[1], r[1])
                    box[2], box[3] = max(box[2], r[2]), max(box[3], r[3])
                    changed = True
            if not changed:
                break
    return boxes


def without_rules_in(g: Graphics, boxes: list[list[float]]) -> Graphics:
    """The same graphics minus the rules that belong to charts (so they can't form tables)."""
    if not boxes:
        return g

    def free(r) -> bool:
        return not any(_inside(r, b, 3) for b in boxes)

    return Graphics(
        hrules=[h for h in g.hrules if free((h[1], h[0], h[2], h[0]))],
        vrules=[v for v in g.vrules if free((v[0], v[1], v[0], v[2]))],
        ink=g.ink,
        images=g.images,
    )


def _label_of(s: Span, box: list[float], body: float) -> bool:
    """Does this text belong to the chart next to it (tick value, axis title, legend entry)?

    Labels are set no bigger than the body text and not bold (that would be a heading).
    Beside the plot only short texts qualify — a line of the neighbouring column must not
    be pulled in; above or below it, axis titles and legend rows may run up to 8 words.
    """
    t = s.text.strip()
    if not t or s.bold or s.size > body * 1.05 or _CAPTION.match(t) or _is_list_start(t):
        return False
    if t.endswith(".") and not t[:-1].replace(",", "").replace(".", "").isdigit():
        return False
    m = max(s.size * 3.5, 18)
    if not _inside((s.x0, s.y0, s.x1, s.y1), (box[0] - m, box[1] - m, box[2] + m, box[3] + m)):
        return False
    beside = s.x1 <= box[0] + 2 or s.x0 >= box[2] - 2
    if beside:
        return len(t) <= 12 or s.height > s.width  # tick values, vertical axis titles
    return len(t) <= 60 and len(t.split()) <= 8 and s.width <= (box[2] - box[0]) * 1.1


def detect_figures(
    g: Graphics,
    spans: list[Span],
    tables: list[Block],
    width: float,
    height: float,
    charts: list[list[float]] | None = None,
    body: float = 10.0,
):
    """Raster images + vector charts. Labels inside (or hugging) a figure belong to it."""
    raster = [list(b) for b in g.images]
    if charts is None:
        charts = chart_regions(g, width, height, spans)
    boxes = [list(b) for b in _cluster_boxes([tuple(b) for b in raster + charts], 2)]
    figures: list[Block] = []
    remaining = list(spans)
    for box in boxes:
        box = [max(0, box[0]), max(0, box[1]), min(width, box[2]), min(height, box[3])]
        if box[2] - box[0] < 12 or box[3] - box[1] < 12:
            continue
        if any(_inside(box, t.bbox, 3) for t in tables):
            continue
        is_raster = any(_inside(r, box, 2) and _inside(box, r, 2) for r in raster)
        inside = [s for s in remaining if _inside((s.x0, s.y0, s.x1, s.y1), box, 2)]
        words = sum(len(s.text.split()) for s in inside)
        text_area = sum(s.width * s.height for s in inside)
        prose = words > 40 or text_area > _area(box) * 0.35
        full_page = _area(box) > width * height * 0.85
        if prose and not full_page:
            # A shaded box behind a paragraph: the text stays prose; keep the art only if raster.
            if not is_raster:
                continue
            inside = []
        elif not is_raster:
            # Tick values and axis titles sit just outside the plot area: take them in
            # (twice, so an axis title outside the tick labels comes along too).
            for _ in range(3):  # axis title, then the legend rows under it
                for s in remaining:
                    if s not in inside and _label_of(s, box, body):
                        inside.append(s)
                        box = [
                            min(box[0], s.x0),
                            min(box[1], s.y0),
                            max(box[2], s.x1),
                            max(box[3], s.y1),
                        ]
        chars = [c for s in inside for c in s.chars]
        figures.append(Block("figure", tuple(box), text=_chars_text(chars)))
        ids = {id(s) for s in inside}
        remaining = [s for s in remaining if id(s) not in ids]
    return figures, remaining


def _area(b) -> float:
    return max(0.0, b[2] - b[0]) * max(0.0, b[3] - b[1])


def _inside(inner, outer, tol: float = 0) -> bool:
    return (
        inner[0] >= outer[0] - tol
        and inner[1] >= outer[1] - tol
        and inner[2] <= outer[2] + tol
        and inner[3] <= outer[3] + tol
    )


def _cluster_boxes(boxes, gap: float) -> list[tuple[float, float, float, float]]:
    boxes = [list(b) for b in boxes]
    changed = True
    while changed:
        changed = False
        out: list[list[float]] = []
        for b in boxes:
            for o in out:
                if (
                    b[0] <= o[2] + gap
                    and o[0] <= b[2] + gap
                    and b[1] <= o[3] + gap
                    and o[1] <= b[3] + gap
                ):
                    o[0], o[1], o[2], o[3] = (
                        min(o[0], b[0]),
                        min(o[1], b[1]),
                        max(o[2], b[2]),
                        max(o[3], b[3]),
                    )
                    changed = True
                    break
            else:
                out.append(b)
        boxes = out
    return [tuple(b) for b in boxes]


# ============================================================================= lines & paragraphs
@dataclass
class Line:
    spans: list[Span]
    x0: float = 0
    y0: float = 0
    x1: float = 0
    y1: float = 0

    def __post_init__(self) -> None:
        self.x0 = min(s.x0 for s in self.spans)
        self.y0 = min(s.y0 for s in self.spans)
        self.x1 = max(s.x1 for s in self.spans)
        self.y1 = max(s.y1 for s in self.spans)

    @property
    def text(self) -> str:
        # (A span that starts with a comma follows an inline icon: "Wu [iD], Fellow".)
        return " ".join(s.text.strip() for s in self.spans if s.text.strip()).replace(" ,", ",")

    @property
    def segments(self) -> list[tuple[str, str]]:
        out: list[tuple[str, str]] = []
        for i, s in enumerate(self.spans):
            if i:
                out.append(("n", " "))
            out += s.segments
        return out

    @property
    def size(self) -> float:
        return max(self.spans, key=lambda s: len(s.chars)).size

    @cached_property
    def italic(self) -> bool:
        slanted = [s.fonts[c.font].italic for s in self.spans for c in s.chars]
        return sum(slanted) >= len(slanted) * 0.9

    @cached_property
    def bold(self) -> bool:
        # By glyph: a line with a few words in bold is not a bold line.
        chars = [c for s in self.spans for c in s.chars]
        return sum(s.fonts[c.font].bold for s in self.spans for c in s.chars) >= len(chars) * 0.9

    def first_word_width(self) -> float:
        chars = [c for s in self.spans for c in s.chars]
        end = next((i for i, c in enumerate(chars[1:], 1) if c.space), len(chars))
        return chars[end - 1].x1 - chars[0].x0

    @property
    def mono(self) -> bool:
        return all(s.mono for s in self.spans)

    @property
    def math(self) -> float:
        n = sum(len(s.chars) for s in self.spans)
        return sum(s.math * len(s.chars) for s in self.spans) / max(n, 1)

    @property
    def has_scripts(self) -> bool:
        return any(k != "n" for s in self.spans for k, _ in s.segments)


def _is_list_start(text: str) -> str | None:
    t = text.lstrip()
    if t[:1] in BULLETS and (len(t) == 1 or t[1:2] == " "):
        return t[0]
    m = _ENUM.match(t)
    return m.group(0) if m else None


def _formula_like(line: Line) -> bool:
    text = line.text
    compact = text.replace(" ", "")
    if not compact or len(compact) > 160 or not any(c.isalnum() for c in compact):
        return False  # "_____" signature lines, dot leaders…
    words = [w for w in re.split(r"\s+", text) if len(w) > 3 and w.isalpha()]
    if len(words) >= 5:
        return False  # prose with a symbol or two
    score = math_score(text)
    return (
        line.math >= 0.4
        or score >= 0.22
        or (line.has_scripts and score >= 0.1)
        or ("=" in text and len(words) <= 1 and any(c.isdigit() or c.isalpha() for c in compact))
    )


def _join_lines(lines: list[Line], edges: dict[int, float] | None = None) -> str:
    """Join wrapped lines with spaces (undoing hyphenation). A break the author made on
    purpose — the next line's first word would have fitted — is kept as a newline."""
    text = ""
    prev: Line | None = None
    for ln in lines:
        t = ln.text.strip()
        if not text:
            text = t
        elif text.endswith("-") and len(text) > 1 and text[-2].isalpha() and t[:1].islower():
            text = text[:-1] + t
        elif edges and prev is not None and _hard_break(prev, ln, edges):
            text += NEWLINE + t
        else:
            text += " " + t
        prev = ln
    return text


def _hard_break(prev: Line, nxt: Line, edges: dict[int, float]) -> bool:
    room = edges.get(id(prev), prev.x1) - prev.x1
    return room > nxt.first_word_width() + max(prev.size, 4) * 0.6


def _right_edges(lines: list[Line]) -> dict[int, float]:
    """Right edge of the text column each line belongs to: the furthest any line reaching
    over it goes. Used to tell a wrapped line from one the author broke on purpose."""
    out = {}
    # Where columns start: an x that three or more lines begin at.
    starts = Counter(round(ln.x0 / 2) for ln in lines)
    col_starts = sorted(k * 2.0 for k, n in starts.items() if n >= 3)
    for a in lines:
        size = max(a.size, 4)
        edge = a.x1
        beside = [x for x in col_starts if x >= a.x1 - 1]
        for b in lines:
            # A centred title over two columns starts well right of a left-column line.
            if min(a.x1, b.x1) - max(a.x0, b.x0) > (a.x1 - a.x0) * 0.5 and b.x0 <= a.x0 + size * 3:
                edge = max(edge, b.x1)
            elif b.x0 >= a.x1 - 1 and min(a.y1, b.y1) - max(a.y0, b.y0) > (a.y1 - a.y0) * 0.5:
                beside.append(b.x0)  # the next column, on the same row
        if beside:
            edge = min(edge, max(a.x1, min(beside) - size))
        out[id(a)] = edge
    # A line that ends exactly where the line above or below does is a full line of a
    # justified block (an abstract set narrower than the body text): it wrapped.
    for i, a in enumerate(lines):
        for b in (lines[i - 1] if i else None, lines[i + 1] if i + 1 < len(lines) else None):
            if b is None or abs(b.x1 - a.x1) > 1.5:
                continue
            size = max(a.size, 4)
            near = min(abs(b.y0 - a.y1), abs(a.y0 - b.y1)) < size * 1.5
            if near and min(a.x1 - a.x0, b.x1 - b.x0) > size * 8:
                out[id(a)] = a.x1
    return out


def _gap(a: Line, b: Line) -> float | None:
    """Vertical gap between two lines of the same text (overlapping, same size), else None."""
    size = max(a.size, 4)
    overlap = min(a.x1, b.x1) - max(a.x0, b.x0)
    gap = b.y0 - a.y1
    if overlap > 0 and abs(a.size - b.size) <= size * 0.15 and -size * 0.5 < gap < size * 2.5:
        return gap
    return None


def _family(name: str) -> str:
    """'ABCDEF+TimesNewRomanPS-BoldMT' -> 'Times New Roman' (what Word calls the font)."""
    base = name.split("+")[-1]
    base = re.split(r"[-,]", base)[0]
    base = re.sub(r"(PSMT|PS|MT)$", "", base)
    # Weight/style words go: bold and italic are carried by the runs.
    base = re.sub(
        r"(Bold|Italic|Oblique|Regular|Semibold|SemiBold|Black|Light|Medium|Book)+$", "", base
    )
    spaced = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", base).strip()
    return spaced or name


def _runs(group: list[Line], edges: dict[int, float]) -> list[dict]:
    """Inline formatting of a paragraph: bold/italic/super/subscript runs, joined exactly like
    _join_lines joins the text (spaces, kept line breaks, undone hyphenation)."""
    runs: list[list] = []

    def add(text: str, bold: bool, italic: bool, script: str | None) -> None:
        if runs and runs[-1][1:] == [bold, italic, script]:
            runs[-1][0] += text
        elif runs and not text.strip():
            runs[-1][0] += text  # spacing keeps the previous run's format
        else:
            runs.append([text, bold, italic, script])

    prev: Line | None = None
    for ln in group:
        if prev is not None and runs:
            last = runs[-1][0]
            first = ln.text.strip()[:1]
            if last.endswith("-") and len(last) > 1 and last[-2].isalpha() and first.islower():
                runs[-1][0] = last[:-1]
            elif _hard_break(prev, ln, edges):
                runs[-1][0] += NEWLINE
            else:
                runs[-1][0] += " "
        for k, span in enumerate(ln.spans):
            if k and runs and not span.text.lstrip().startswith(","):
                runs[-1][0] += " "
            fonts = span.fonts
            piece: list[Char] = []
            prior: Char | None = None  # the glyph before this piece, on the same span
            for ch in [*span.chars, None]:
                fmt = None if ch is None else (fonts[ch.font].bold, fonts[ch.font].italic)
                if piece and (
                    ch is None or fmt != (fonts[piece[0].font].bold, fonts[piece[0].font].italic)
                ):
                    f = fonts[piece[0].font]
                    gap = piece[0].x0 - prior.x1 if prior else 0.0
                    spaced = (piece[0].space or gap > max(span.size, 1) * WORD_GAP_EM) and (
                        piece[0].c != "," or piece[0].space == 2
                    )
                    lead = (
                        " " if spaced and runs and not runs[-1][0].endswith((" ", NEWLINE)) else ""
                    )
                    prior = piece[-1]
                    for i, (kind, text) in enumerate(_segments(piece, span.size)):
                        script = None if kind == "n" else ("super" if kind == "sup" else "sub")
                        text = plain_math(text)
                        add((lead if i == 0 else "") + text, f.bold, f.italic, script)
                    piece = []
                if ch is not None:
                    piece.append(ch)
        prev = ln
    out = [{"text": t, "bold": b, "italic": i, "script": s} for t, b, i, s in runs if t]
    if out:
        out[0]["text"] = out[0]["text"].lstrip()
        out[-1]["text"] = out[-1]["text"].rstrip()
    return out


def _strip_prefix(runs: list[dict], prefix: str) -> list[dict]:
    """Remove a list marker from the start of the runs."""
    n = len(prefix)
    for r in runs:
        if n <= 0:
            break
        cut = min(n, len(r["text"]))
        r["text"], n = r["text"][cut:], n - cut
    runs = [r for r in runs if r["text"]]
    if runs:
        runs[0]["text"] = runs[0]["text"].lstrip()
    return runs


def _tracking(group: list[Line]) -> float | None:
    """Letter spacing of a "T Í T U L O": the usual gap between letters of the same word."""
    gaps = []
    for ln in group:
        for s in ln.spans:
            for a, b in zip(s.chars, s.chars[1:], strict=False):
                if not b.space:
                    gaps.append(b.x0 - a.x1)
    if len(gaps) < 4:
        return None
    gap = statistics.median(gaps)
    size = statistics.median(ln.size for ln in group)
    return round(gap, 1) if gap > size * 0.08 else None


def _layout_format(page: Page) -> None:
    """Alignment, indents and line spacing of each text block, against its column."""
    text_blocks = [b for b in page.blocks if b.line_boxes and b.type not in FURNITURE]
    if not text_blocks:
        return
    skip = (*FURNITURE, "figure")  # a grid of pictures has gaps that are not gutters
    cols = columns([b.bbox for b in page.blocks if b.bbox and b.type not in skip])
    for b in text_blocks:
        left, right = area_of(b.bbox, cols)
        width = max(right - left, 1.0)
        mid = (left + right) / 2
        tol = max(3.0, width * 0.012)
        boxes = b.line_boxes
        x0s = [x0 for x0, _, _, _ in boxes]
        x1s = [x1 for _, _, x1, _ in boxes]
        centred = all(abs((a + c) / 2 - mid) <= tol * 1.5 for a, c in zip(x0s, x1s, strict=True))
        if (
            len(boxes) >= 2
            and all(abs(e - right) <= tol for e in x1s[:-1])
            and min(x0s) <= left + tol
        ):
            b.align = "justify"
        elif centred and min(x0s) > left + width * 0.05:
            b.align = "center"
        elif all(abs(e - right) <= tol for e in x1s) and min(x0s) > left + width * 0.3:
            b.align = "right"
        else:
            b.align = "left"
        if b.align in ("left", "justify"):
            base = min(x0s[1:]) if len(boxes) > 1 else x0s[0]
            if base - left > tol:
                b.indent = round(base - left, 1)
            if len(boxes) > 1 and abs(x0s[0] - base) > tol:
                b.first_line = round(x0s[0] - base, 1)
        if len(boxes) >= 2 and b.pt:
            pitch = statistics.median(boxes[k + 1][3] - boxes[k][3] for k in range(len(boxes) - 1))
            multiple = pitch / (b.pt * 1.15)  # Word's "single" is ~1.15 em for common fonts
            if multiple > 1.2:
                b.line_spacing = round(multiple, 2)
            if b.pt * 0.9 <= pitch <= b.pt * 3:
                b.leading = round(pitch, 1)


def _same_leading(gap: float, size: float, group: list[Line], lines: list[Line], idx: int) -> bool:
    """Is this gap a line break inside a paragraph? Either it's small, or it equals the
    spacing of the neighbouring lines (1.5- and double-spaced documents)."""
    if gap <= -size * 0.5:
        return False
    if gap <= size * PARA_GAP_EM:
        return True
    if gap > size * 1.6:
        return False
    near = []
    if len(group) >= 2:
        near.append(_gap(group[-2], group[-1]))
    if idx + 1 < len(lines):
        near.append(_gap(lines[idx], lines[idx + 1]))
    return any(g is not None and abs(g - gap) <= max(1.5, gap * 0.2) for g in near)


def lines_to_blocks(lines: list[Line], body: float) -> list[Block]:
    blocks: list[Block] = []
    group: list[Line] = []
    kind = "paragraph"
    edges = _right_edges(lines) if len(lines) > 1 else {}

    def flush():
        nonlocal group, kind
        if not group:
            return
        x0 = min(ln.x0 for ln in group)
        y0 = min(ln.y0 for ln in group)
        x1 = max(ln.x1 for ln in group)
        y1 = max(ln.y1 for ln in group)
        size = statistics.median(ln.size for ln in group)
        bold = all(ln.bold for ln in group)
        if kind == "code":
            text = "\n".join(_indent(ln, x0, size) + ln.text for ln in group)
            b = Block("code", (x0, y0, x1, y1), text=text)
        elif kind == "formula":
            segs: list[tuple[str, str]] = []
            number = None
            for ln in group:
                spans = list(ln.spans)
                if len(spans) > 1 and _EQ_NUMBER.match(spans[-1].text.strip()):
                    number = spans.pop().text.strip()
                if segs:
                    segs.append(("n", " "))
                segs += Line(spans).segments
            b = Block(
                "formula",
                (x0, y0, x1, y1),
                text=segments_text(segs).strip(),
                latex=segments_latex(segs),
                number=number,
            )
        else:
            text = _join_lines(group, edges)
            b = Block(kind, (x0, y0, x1, y1), text=text)
            # Runs only where formatting varies (or isn't plain): most paragraphs are neither.
            looks = {
                (s.fonts[c.font].bold, s.fonts[c.font].italic)
                for ln in group
                for s in ln.spans
                for c in s.chars
            }
            plain = looks == {(False, False)} and not any(ln.has_scripts for ln in group)
            runs = [] if plain else _runs(group, edges)
            if kind == "list_item":
                b.marker = _is_list_start(text)
                b.text = text.lstrip()[len(b.marker) :].strip() if b.marker else text
                if b.marker and runs:
                    runs = _strip_prefix(runs, b.marker)
            # Only when formatting varies (or isn't plain): plain text needs no runs.
            if len(runs) > 1 or (
                runs and (runs[0]["bold"] or runs[0]["italic"] or runs[0]["script"])
            ):
                b.runs = runs
            b.line_boxes = [(ln.x0, ln.y0, ln.x1, ln.y1) for ln in group]
        glyph_fonts = [s.fonts[c.font] for ln in group for s in ln.spans for c in s.chars]
        pts = [f.pt for f in glyph_fonts if f.pt]
        if pts:
            b.pt = round(statistics.median(pts), 1)
        b.tracking = _tracking(group)
        families = Counter(f.name for f in glyph_fonts if f.name)
        if families:
            b.font = _family(families.most_common(1)[0][0])
        b.font_size, b.bold, b.lines = size, bold, len(group)
        blocks.append(b)
        group = []
        kind = "paragraph"

    for idx, ln in enumerate(lines):
        text = ln.text
        if not text.strip():
            continue
        this_kind = "paragraph"
        if ln.mono and len(text) > 1:
            this_kind = "code"
        elif _formula_like(ln):
            this_kind = "formula"
        elif _is_list_start(text):
            this_kind = "list_item"
        if group:
            prev = group[-1]
            size = max(prev.size, 4)
            gap = ln.y0 - prev.y1
            overlap = min(prev.x1, ln.x1) - max(prev.x0, ln.x0)
            same_style = abs(ln.size - prev.size) <= size * 0.15 and ln.bold == prev.bold
            continues = _same_leading(gap, size, group, lines, idx) and overlap > 0 and same_style
            if kind == "code":
                continues = this_kind == "code" and gap <= size * 1.2 and overlap > -size
            elif kind == "formula":
                continues = this_kind == "formula" and gap <= size * 0.9
            elif this_kind in ("list_item", "formula", "code"):
                continues = False
            elif kind == "list_item":
                # Wrapped item text is either indented under the text (hanging indent) or
                # flush with the marker — the latter only right after a full-width line.
                first = group[0]
                indent_ok = ln.x0 >= first.x0 + size * 0.3
                wrapped = ln.x0 >= first.x0 - 2 and prev.x1 >= max(g.x1 for g in group) - size * 2
                # (A first line cut short on purpose is a heading line, not an item.)
                continues = (
                    continues
                    and (indent_ok or wrapped)
                    and not _hard_break(prev, ln, edges)
                    # ("A. Related Work" in italics, then its paragraph in upright type.)
                    and not (group[0].italic and not ln.italic)
                )
            else:
                text_so_far = prev.text.rstrip()
                short_prev = prev.x1 < max(g.x1 for g in group) - size * 2.5
                if short_prev and text_so_far[-1:] in ".:!?":
                    continues = False
                if ln.x0 > prev.x0 + size * 0.9 and len(group) >= 1 and not short_prev:
                    continues = False  # first-line indent starts a new paragraph
            if not continues:
                flush()
        if not group:
            kind = this_kind
        group.append(ln)
    flush()
    return blocks


def _indent(ln: Line, x0: float, size: float) -> str:
    return " " * max(0, round((ln.x0 - x0) / max(size * 0.6, 1)))


# ============================================================================= page analysis
@dataclass
class PageResult:
    page: Page
    sizes: Counter  # char size -> count, for the document body size
    chars: int
    map_errors: int


def analyze_page(pdf: pdfium.PdfDocument, index: int, opts: LayoutOptions) -> PageResult:
    page = pdf[index]
    try:
        # Effective visible box. (get_cropbox() ignores a MediaBox inherited from /Pages
        # and silently falls back to US Letter.)
        crop = page.get_bbox()
        width, height = crop[2] - crop[0], crop[3] - crop[1]
        producer = pdf.get_metadata_value("Producer") or ""
        chars, rotated, fonts, map_errors = read_chars(page, crop, is_tex_producer(producer))
        g = read_graphics(page, crop, width, height)
        if any(f.white for f in fonts):
            chars, rotated = _visible(page, chars + rotated, fonts, g, width, height, rotated)
        page_gaps: list = []
        chars = _typeset_math(chars, g)
        spans = build_spans(chars, fonts, page_gaps) if chars else []
        rot_spans = [Span(grp, fonts) for grp in _group_rotated(rotated)]
        sizes: Counter = Counter(round(c.size * 2) / 2 for c in chars)
        body = sizes.most_common(1)[0][0] if sizes else 10.0

        # Charts first: their axes, ticks and legend frame are rules too, and must not be
        # mistaken for a table grid.
        charts = chart_regions(g, width, height)
        tables: list[Block] = []
        if opts.detect_tables:
            tables, spans = detect_ruled_tables(spans, without_rules_in(g, charts))
        figures, spans = detect_figures(g, spans + rot_spans, tables, width, height, charts, body)

        atoms = [Atom("span", s.x0, s.y0, s.x1, s.y1, span=s) for s in spans]
        atoms += [Atom(b.type, *b.bbox, block=b) for b in tables + figures]
        # Text is set in two or three columns; more gutters than that are a table's.
        text_gaps = page_gaps if len(page_gaps) <= 2 else []
        bands = reading_order(atoms, max(GUTTER_MIN, body * 0.8), text_gaps)

        blocks: list[Block] = []
        pending: list[Line] = []
        i = 0
        while i < len(bands):
            band = bands[i]
            if len(band) == 1 and band[0].kind != "span":
                blocks += lines_to_blocks(pending, body)
                pending = []
                blocks.append(band[0].block)
                i += 1
                continue
            if opts.detect_tables and len(band) >= 2:
                table, j = unruled_table(bands, i, body)
                if table is not None:
                    blocks += lines_to_blocks(pending, body)
                    pending = []
                    blocks.append(table)
                    i = j
                    continue
            spans_in = [a.span for a in band if a.span]
            for a in band:
                if a.kind != "span":
                    blocks += lines_to_blocks(pending, body)
                    pending = []
                    blocks.append(a.block)
            if spans_in:
                pending.append(Line(spans_in))
            i += 1
        blocks += lines_to_blocks(pending, body)
        if not opts.detect_formulas:
            for b in blocks:
                if b.type == "formula":
                    b.type = "paragraph"

        result = Page(index + 1, width, height, blocks)
        result.scanned = not chars and any(_area(b) > width * height * 0.5 for b in g.images)
        if opts.images:
            _attach_images(page, result, opts)
        return PageResult(result, sizes, len(chars), map_errors)
    finally:
        page.close()


def _visible(page, chars, fonts, g, width, height, rotated_list):
    """Drop white text on white paper — generators use it to align things ("Situação do
    vínculo: (X)" repeated in white before each option). Kept: white on a coloured cell, and
    a white glyph that PDFium merged with an identical visible glyph drawn on top of it
    (it drops such duplicates as "fake bold") — detected by ink in the rendered page where
    no other visible glyph is."""
    from PIL import ImageDraw

    under = g.fills + g.images
    hidden = [
        c
        for c in chars
        if fonts[c.font].white
        and not any(b[0] <= c.cx <= b[2] and b[1] <= c.cy <= b[3] for b in under)
    ]
    if not hidden:
        return [c for c in chars if c not in rotated_list], rotated_list
    scale = 2.0
    img = page.render(scale=scale, rotation=0, grayscale=True).to_pil().convert("L")
    draw = ImageDraw.Draw(img)
    for c in chars:  # erase what we already know is visible
        if c not in hidden:
            draw.rectangle([c.x0 * scale, c.y0 * scale, c.x1 * scale, c.y1 * scale], fill=255)
    drop = set()
    for c in hidden:
        w, h = c.x1 - c.x0, c.y1 - c.y0
        box = (
            int((c.x0 + w * 0.15) * scale),
            int((c.y0 + h * 0.2) * scale),
            int((c.x1 - w * 0.15) * scale) + 1,
            int((c.y1 - h * 0.2) * scale) + 1,
        )
        hist = img.crop(box).histogram()
        total = sum(hist) or 1
        if sum(hist[:128]) / total < 0.04:
            drop.add(id(c))
    rot_ids = {id(c) for c in rotated_list}
    kept = [c for c in chars if id(c) not in drop]
    return [c for c in kept if id(c) not in rot_ids], [c for c in kept if id(c) in rot_ids]


def _group_rotated(chars: list[Char]) -> list[list[Char]]:
    groups: list[list[Char]] = []
    for ch in chars:
        if groups:
            last = groups[-1][-1]
            d = max(ch.size, ch.x1 - ch.x0) * 3  # rotated glyph: its box is turned too
            if abs(ch.cx - last.cx) < d and abs(ch.cy - last.cy) < d:
                groups[-1].append(ch)
                continue
        groups.append([ch])
    return groups


def _attach_images(page: pdfium.PdfPage, result: Page, opts: LayoutOptions) -> None:
    wanted = {"figure"}
    if opts.table_images:
        wanted.add("table")
    if opts.formula_images:
        wanted.add("formula")
    targets = [b for b in result.blocks if b.type in wanted and b.bbox]
    if not targets:
        return
    scale = opts.image_scale
    W, H = result.width, result.height
    counters: Counter = Counter()
    for b in targets:
        pad = 3
        x0, y0 = max(0.0, b.bbox[0] - pad), max(0.0, b.bbox[1] - pad)
        x1, y1 = min(W, b.bbox[2] + pad), min(H, b.bbox[3] + pad)
        if (x1 - x0) * scale < 4 or (y1 - y0) * scale < 4:
            continue
        # Render only this region: crop = what to cut from (left, bottom, right, top).
        bitmap = page.render(scale=scale, rotation=0, crop=(x0, H - y1, W - x1, y0))
        img = bitmap.to_pil()
        bitmap.close()
        buf = io.BytesIO()
        img.save(buf, format="PNG", compress_level=6)
        counters[b.type] += 1
        name = f"p{result.number}-{b.type}-{counters[b.type]}.png"
        b.image = ImageData(name, "image/png", img.width, img.height, buf.getvalue())


def analyze_pages(
    source, password: str | None, indices: list[int], opts: LayoutOptions
) -> list[PageResult]:
    """Top-level (picklable) entry point: analyse some pages of a document."""
    pdf = pdfium.PdfDocument(source, password=password)
    try:
        return [analyze_page(pdf, i, opts) for i in indices]
    finally:
        pdf.close()


# ============================================================================= document passes
def _signature(text: str) -> str:
    return re.sub(r"\d+", "#", " ".join(strip_accents_lower(text).split()))


def finalize(results: list[PageResult], heading_hints: dict[str, int] | None = None) -> list[Page]:
    pages = [r.page for r in results]
    total: Counter = Counter()
    for r in results:
        total.update(r.sizes)
    body = total.most_common(1)[0][0] if total else 10.0

    _mark_furniture(pages)
    _normalize_sizes(pages, body)
    _classify_headings(pages, body, heading_hints or {})
    _merge_heading_lines(pages, body)
    for p in pages:
        _absorb_formula_bits(p)
        _compose_figures(p, body)
        _link_captions(p)
        _layout_format(p)
        for n, b in enumerate(p.blocks):
            b.order = n
            b.id = f"p{p.number}-b{n}"
    return pages


def _furniture_key(b: Block) -> str:
    if b.type == "figure":  # a logo repeated on every page: same place, same size
        x0, y0, x1, y1 = b.bbox
        return f"fig:{round(x0 / 6)},{round(y0 / 6)},{round((x1 - x0) / 6)},{round((y1 - y0) / 6)}"
    return re.sub(r"^(# )+|( #)+$", "", _signature(b.text))  # "8836 IEEE TRANS…" = "IEEE TRANS…"


def _mark_furniture(pages: list[Page]) -> None:
    def zone(b: Block, p: Page) -> str | None:
        if b.bbox is None or b.type not in ("paragraph", "heading", "list_item", "figure"):
            return None
        x0, y0, x1, y1 = b.bbox
        narrow_tall = x1 - x0 < p.width * 0.06 and y1 - y0 > p.height * 0.1
        in_margin = x1 <= p.width * 0.1 or x0 >= p.width * 0.9
        if b.type != "figure" and narrow_tall and in_margin:
            return "margin"  # vertical stamp in the side margin (arXiv id, "Draft", line ids)
        if b.bbox[3] <= p.height * EDGE_ZONE + 20 or (
            b.type == "figure" and b.bbox[1] <= p.height * EDGE_ZONE
        ):
            return "header"
        if b.bbox[1] >= p.height * (1 - EDGE_ZONE) - 20:
            return "footer"
        return None

    counts: Counter = Counter()
    for p in pages:
        counts.update({(zone(b, p), _furniture_key(b)) for b in p.blocks if zone(b, p)})
    need = max(2, math.ceil(len(pages) * 0.3))  # running heads alternate on odd/even pages
    for p in pages:
        for b in p.blocks:
            z = zone(b, p)
            if not z:
                continue
            key = _furniture_key(b)
            if z == "margin":
                b.type = "header"
            elif b.type != "figure" and _PAGE_NUMBER.fullmatch(b.text.strip()):
                b.type = "page_number"
            elif (
                len(pages) >= 2
                and counts[(z, key)] >= (2 if b.type == "figure" else need)
                and len(key) >= 3
            ):
                b.type = z
            elif len(pages) >= 2 and b.type != "figure":
                # A running stamp glued to another line of the margin ("©2026 IEEE" +
                # "Authorized licensed use…").
                for (cz, stamp), n in counts.items():
                    if (
                        cz == z
                        and n >= need
                        and len(stamp) >= 20
                        and len(stamp) >= len(key) * 0.5
                        and stamp in key
                    ):
                        b.type = z
                        break


def _section_number(b: Block, body: float) -> bool:
    """A one-line 'list item' set bold or bigger than the body text is a numbered heading."""
    if b.lines != 1 or not b.marker or len(b.text) > 80:
        return False
    if re.fullmatch(r"[IVX]{1,4}\.", b.marker):  # "I. INTRODUCTION" in small caps
        letters = [c for c in b.text if c.isalpha()]
        return len(letters) >= 4 and all(c.isupper() for c in letters)
    if re.fullmatch(r"[A-Z]\.", b.marker):  # "A. Image Denoising": a subsection
        text = b.text.strip()
        return (
            len(text) <= 70
            and text[-1:] not in ".,;:"
            and text[:1].isupper()
            and len(text.split()) <= 10
        )
    if not b.marker[0].isdigit():
        return False
    return (b.font_size or body) >= body * 1.25 or (b.bold and not b.text.rstrip().endswith("."))


def _normalize_sizes(pages: list[Page], body: float) -> None:
    """The height of a glyph box depends on the font's metrics: a 14 pt bold title can come
    out shorter than 12 pt author names. Blocks are compared by their real size instead,
    scaled so that body text keeps its box height."""
    weight: Counter = Counter()
    for p in pages:
        for b in p.blocks:
            if b.pt and b.text and b.type == "paragraph":
                weight[round(b.pt * 2) / 2] += len(b.text)
    if not weight:
        return
    body_pt = weight.most_common(1)[0][0]
    for p in pages:
        for b in p.blocks:
            if b.pt and b.font_size:
                b.font_size = b.pt / body_pt * body


def _front_matter(pages: list[Page], body: float) -> set[int]:
    """Blocks between the title and the abstract of the first page: authors and affiliations,
    often set bigger than the body, but not headings."""
    if not pages or pages[0].number != 1:
        return set()
    blocks = pages[0].blocks

    def size(b: Block) -> float:
        return b.font_size or body

    title_size = max([body, *(size(b) for b in blocks if b.type == "paragraph" and b.text)])
    title = next(
        (
            i
            for i, b in enumerate(blocks)
            if b.type == "paragraph" and b.text and size(b) >= title_size * 0.98
        ),
        None,
    )
    if title is None or title_size < body * 1.3:
        return set()
    head = blocks[title]
    abstract = next(
        (
            b
            for b in blocks[title + 1 :]
            if b.bbox
            and b.text
            and re.match(r"(abstract|resumo|summary)", b.text.strip(), re.IGNORECASE)
        ),
        None,
    )
    if abstract is None or not head.bbox:
        return set()
    # By position: on a two-column page the second author comes later in reading order.
    return {
        id(b)
        for b in blocks
        if b is not head
        and b.bbox
        and b.bbox[1] >= head.bbox[3] - 2
        and b.bbox[3] <= abstract.bbox[1] + 2
        and size(b) < title_size * 0.9
    }


_TABLE_LABEL = re.compile(r"(table|tabela|quadro)\s+[ivxlc\d]+\.?$", re.IGNORECASE)
_HEADING_START = re.compile(r"([IVX]{1,4}|[A-Z])\.\s|(appendix|ap[eê]ndice|anexo)\b", re.IGNORECASE)


def _table_title(prev: Block, titles: set[int]) -> bool:
    return id(prev) in titles or bool(_TABLE_LABEL.match((prev.text or "").strip()))


def _merge_heading_lines(pages: list[Page], body: float) -> None:
    """A title set on two lines (centred, or cut at a hyphen) is one heading."""
    for p in pages:
        out: list[Block] = []
        for b in p.blocks:
            a = out[-1] if out else None
            if (
                a is not None
                and a.type == "heading"
                and b.type == "heading"
                and a.level == b.level
                and a.bbox
                and b.bbox
                and not _NUMBERED_HEADING.match(b.text)
                and not re.match(r"([IVX]{1,4}|[A-Z])\.\s", b.text)
                and not re.match(r"(appendix|ap[eê]ndice|anexo)\b", b.text, re.IGNORECASE)
                and abs((a.font_size or body) - (b.font_size or body)) <= body * 0.1
                and a.bold == b.bold
                and b.bbox[1] - a.bbox[3] < (b.font_size or body) * 0.9
                and b.bbox[1] >= a.bbox[1]
                and min(a.bbox[2], b.bbox[2]) - max(a.bbox[0], b.bbox[0]) > 0
            ):
                hyphen = len(a.text) > 1 and a.text.endswith("-") and a.text[-2].isalpha()
                a.text = a.text[:-1] + b.text if hyphen else f"{a.text} {b.text}"
                a.bbox = (
                    min(a.bbox[0], b.bbox[0]),
                    a.bbox[1],
                    max(a.bbox[2], b.bbox[2]),
                    max(a.bbox[3], b.bbox[3]),
                )
                a.lines += b.lines
                a.runs = None  # one style for the whole title
                if a.line_boxes and b.line_boxes:
                    a.line_boxes = [*a.line_boxes, *b.line_boxes]
                continue
            out.append(b)
        p.blocks = out


def _bold_section(b: Block, body: float) -> bool:
    """ "3. Method" / "3.1. Setup" in bold and bigger than the body: sections, even one right
    after the other."""
    return bool(
        b.bold
        and re.fullmatch(r"\d+(\.\d+)*\.?", b.marker or "")
        and b.lines <= 2
        and len(b.text) <= 120
        and not b.text.rstrip().endswith(".")
        and (b.font_size or body) >= body * 1.05
    )


def _classify_headings(pages: list[Page], body: float, hints: dict[str, int]) -> None:
    candidates: list[tuple[Block, str]] = []
    titles: set[int] = set()
    front = _front_matter(pages, body)
    for p in pages:
        blocks = p.blocks
        for i, b in enumerate(blocks):
            neighbours = [x.type for x in blocks[max(0, i - 1) : i] + blocks[i + 1 : i + 2]]
            lone = "list_item" not in neighbours and _section_number(b, body)
            # "II. METHOD", "A. Image Denoising": a title by its form, unless "B." follows
            # right away (then it is a list).
            titled = False
            if b.type == "list_item" and re.fullmatch(r"[IVX]{1,4}\.|[A-Z]\.", b.marker or ""):
                near = blocks[max(0, i - 1) : i] + blocks[i + 1 : i + 2]
                listed = len(b.marker) == 2 and any(
                    x.type == "list_item" and re.fullmatch(r"[A-Z]\.", x.marker or "") for x in near
                )
                titled = not listed and _section_number(b, body)
            if b.type == "list_item" and (lone or titled or _bold_section(b, body)):
                if b.runs:  # the number is part of the title
                    b.runs[0]["text"] = f"{b.marker} {b.runs[0]['text']}"
                b.text = f"{b.marker} {b.text}"  # "1. Introduction" is a numbered section
                b.type, b.marker = "paragraph", None
            if b.type != "paragraph" or not b.text:
                continue
            if titled:
                candidates.append((b, "bold"))
                continue
            text = b.text.strip()
            key = _signature(text)
            if key in hints:
                b.type, b.level = "heading", hints[key]
                continue
            if b.lines > 3 or len(text) > 200 or text[-1:] in ",;" or _CAPTION.match(text):
                continue
            if not _WORD.search(text) or id(b) in front:
                continue  # axis ticks, a lone number; authors under the title
            size = b.font_size or body
            nxt = next((x for x in blocks[i + 1 :] if x.type not in FURNITURE), None)
            letters = [c for c in text if c.isalpha()]
            caps = len(letters) >= 4 and all(c.isupper() for c in letters) and len(text) <= 90
            # "Centro de Custo: 88.530" is a field; "FCR: Robust…" in title size is a title.
            key_value = bool(_KEY_VALUE.match(text)) and size < body * 1.4
            if size >= body * 1.18 and not key_value:
                candidates.append((b, "size"))
            elif key_value:
                continue
            elif (b.bold and len(text) <= 140 and b.lines <= 2 and text[-1:] != "."
                  and (nxt is None or not nxt.bold or nxt.type != "paragraph")):  # fmt: skip
                candidates.append((b, "bold"))
            elif caps and i and _table_title(blocks[i - 1], titles):
                b.type = "caption"  # "TABLE I", then its title in capitals on the next lines
                titles.add(id(b))
            elif caps and b.lines == 1 and text[-1:] != ".":
                candidates.append((b, "caps"))
    size_levels = sorted(
        {round((b.font_size or body) * 2) / 2 for b, why in candidates if why == "size"},
        reverse=True,
    )
    size_levels = size_levels[:3]
    top = len(size_levels)
    for b, why in candidates:
        b.type = "heading"
        m = _NUMBERED_HEADING.match(b.text)
        if why == "size":
            key = round((b.font_size or body) * 2) / 2
            b.level = size_levels.index(key) + 1 if key in size_levels else top
        else:
            b.level = min(6, top + 1)
        if m and why != "size":
            b.level = min(6, max(b.level, m.group(1).count(".") + 1 + (1 if top else 0)))


def _absorb_formula_bits(page: Page) -> None:
    """A displayed formula is drawn in pieces: the big "∑", its limits, the body. Pieces of
    one or two glyphs that ended up as blocks of their own go back into the formula beside
    them."""

    def bit(b: Block) -> bool:
        t = b.text.strip()
        return (
            b.type == "paragraph"
            and bool(b.bbox)
            and len(t) <= 2
            and not (len(t) == 2 and t.isalpha())
        )

    keep: list[Block] = []
    for b in page.blocks:
        if not bit(b):
            keep.append(b)
            continue
        size = max(b.bbox[3] - b.bbox[1], 6)
        best, best_gap = None, math.inf
        for f in page.blocks:
            if f.type != "formula" or not f.bbox:
                continue
            dx = max(f.bbox[0] - b.bbox[2], b.bbox[0] - f.bbox[2], 0)
            dy = max(f.bbox[1] - b.bbox[3], b.bbox[1] - f.bbox[3], 0)
            if dx <= size * 1.5 and dy <= size * 1.2 and dx + dy < best_gap:
                best, best_gap = f, dx + dy
        if best is None:
            keep.append(b)
            continue
        t = b.text.strip()
        before = b.bbox[2] <= best.bbox[0] + 2
        best.text = f"{t} {best.text}" if before else f"{best.text} {t}"
        if best.latex:
            tex = latex_escape(t)
            best.latex = f"{tex} {best.latex}" if before else f"{best.latex} {tex}"
        best.bbox = (
            min(best.bbox[0], b.bbox[0]),
            min(best.bbox[1], b.bbox[1]),
            max(best.bbox[2], b.bbox[2]),
            max(best.bbox[3], b.bbox[3]),
        )
    page.blocks = keep


_WORD = re.compile(r"[^\W\d_]{3}")  # three letters in a row
_FIGURE_CAPTION = re.compile(r"^(fig|gr[aá]fico|chart|imagem|image|esquema|diagram)", re.IGNORECASE)


def _compose_figures(page: Page, body: float) -> None:
    """A figure made of several pictures with labels around them (sub-titles, "(a)", axis
    ticks): what is stacked right above a "Figure N" caption, down to the caption, is one
    figure."""

    def live(b: Block) -> bool:
        return bool(b.bbox) and b.type not in FURNITURE

    def is_caption(b: Block) -> bool:
        return b.type in ("paragraph", "heading", "caption") and _caption_text(b.text.strip())

    def label(b: Block, first: bool = False) -> bool:
        if b.type == "figure":
            return True
        if is_caption(b):
            return False
        t = b.text or ""
        if b.type == "table":
            return len(t) <= 400 or first  # right above the caption: a chart
        numbered = _NUMBERED_HEADING.match(t) or re.match(r"[IVX]+\.\s", t)
        if b.type == "heading" and _WORD.search(t) and numbered:
            return False
        small = (b.font_size or body) < body * 0.88
        return (b.lines <= 2 and len(t) <= 60) or (small and len(t) <= 250)

    # Text printed inside a picture (ticks, legend) is part of it.
    for fig in [b for b in page.blocks if b.type == "figure" and b.bbox]:
        within = [
            b
            for b in page.blocks
            if b is not fig
            and live(b)
            and b.type != "figure"
            and label(b)
            and _inside(b.bbox, fig.bbox, 2)
        ]
        if not within:
            continue
        texts = [fig.text, *((b.text or "").strip() for b in within)]
        fig.text = NEWLINE.join(t for t in texts if t)
        gone = {id(b) for b in within}
        page.blocks = [b for b in page.blocks if id(b) not in gone]

    cols = columns([b.bbox for b in page.blocks if live(b) and b.type != "figure"])
    captions = [
        b
        for b in page.blocks
        if live(b) and is_caption(b) and _FIGURE_CAPTION.match(b.text.strip())
    ]
    for cap in captions:
        left, right = area_of(cap.bbox, cols) if cols else (-math.inf, math.inf)
        above = sorted(
            (
                b
                for b in page.blocks
                if b is not cap
                and live(b)
                and b.bbox[3] <= cap.bbox[1] + 3
                and b.bbox[0] >= left - 3
                and b.bbox[2] <= right + 3
            ),
            key=lambda b: -b.bbox[3],
        )
        parts: list[Block] = []
        top = cap.bbox[1]
        for b in above:
            if b.bbox[3] < top - 28:
                break  # white space: the figure ended
            if label(b, not parts):
                parts.append(b)
                top = min(top, b.bbox[1])
            elif b.bbox[3] <= top + 2:
                break  # body text above
        # Under a "Figure" caption, a grid of rules with text is a chart, not a table.
        pictures = [b for b in parts if b.type == "figure"] or [
            b for b in parts if b.type == "table"
        ]
        if not pictures and len(parts) >= 6:
            pictures = parts  # a chart drawn with no frame: only its labels
        if not pictures:
            continue
        # Above the topmost picture only its title belongs: centred on a picture, or small print.
        picture_top = min(b.bbox[1] for b in pictures)

        def belongs(b: Block, picture_top=picture_top, pictures=pictures) -> bool:
            if any(b is p for p in pictures) or b.bbox[3] > picture_top + 2:
                return True
            if b.bbox[3] < picture_top - 14:
                return False
            mid = (b.bbox[0] + b.bbox[2]) / 2
            centred = any(
                abs((p.bbox[0] + p.bbox[2]) / 2 - mid) <= (p.bbox[2] - p.bbox[0]) * 0.2
                for p in pictures
            )
            return centred or (b.font_size or body) < body * 0.88

        parts = [b for b in parts if belongs(b)]
        if len(parts) < 2 and parts[0].type == "figure":
            continue
        parts.sort(key=lambda b: (b.bbox[1], b.bbox[0]))
        bbox = (
            min(b.bbox[0] for b in parts),
            min(b.bbox[1] for b in parts),
            max(b.bbox[2] for b in parts),
            max(b.bbox[3] for b in parts),
        )
        text = NEWLINE.join(t for t in ((b.text or "").strip() for b in parts) if t)
        ids = {id(b) for b in parts}
        at = min(i for i, b in enumerate(page.blocks) if id(b) in ids)
        figure = Block("figure", bbox, text=text)
        page.blocks = (
            [b for b in page.blocks[:at] if id(b) not in ids]
            + [figure]
            + [b for b in page.blocks[at:] if id(b) not in ids]
        )


def _caption_text(t: str) -> bool:
    """ "Table 1 presents the results…" is a sentence; "Table 1: Results" and "Table 1 Results"
    are captions."""
    m = _CAPTION.match(t)
    if not m:
        return False
    if m.group(0).rstrip()[-1:] in ".:-–—|":
        return True
    rest = t[m.end() :].lstrip()
    return not rest or not rest[0].islower()


def _link_captions(page: Page) -> None:
    targets = [b for b in page.blocks if b.type in ("figure", "table") and b.bbox]
    for b in page.blocks:
        if (
            b.type not in ("paragraph", "heading")
            or not b.bbox
            or not _caption_text(b.text.strip())
        ):
            continue
        if len(b.text) > 900:
            continue
        best, dist = None, math.inf
        for t in targets:
            overlap = min(b.bbox[2], t.bbox[2]) - max(b.bbox[0], t.bbox[0])
            if overlap <= 0:
                continue
            d = min(abs(b.bbox[1] - t.bbox[3]), abs(t.bbox[1] - b.bbox[3]))
            if d < dist:
                best, dist = t, d
        if best is not None and dist <= 60:
            b.type = "caption"
            b.level = None
            if best.caption is None:
                best.caption = b.text
        elif b.lines <= 3 and _STRICT_CAPTION.match(b.text.strip()):
            b.type = "caption"
            b.level = None
