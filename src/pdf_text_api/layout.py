"""Geometric layout analysis on top of PDFium.

Pipeline for one page (all coordinates top-left origin, in points):

    chars ──► spans (runs on one baseline, split at wide gaps; super/subscripts kept)
    paths/images ──► rules, ruled tables, figures
    spans + atoms ──► column-aware XY-cut ──► bands in reading order
    bands ──► unruled tables, lines ──► paragraphs, lists, formulas, code

Document-level passes (headings by font size, running headers/footers, captions)
live in `finalize()` so pages can be analysed in parallel processes.

The browser engine (`docs/assets/engine.js`) implements the same algorithm on top
of pdf.js; thresholds are named alike in both files.
"""

