# ----------------------------------------------------------------------------- tunables
SPAN_GAP_EM = 0.9  # gap (in font sizes) that splits a line into separate spans
JUSTIFIED_GAP_EM = 2.6  # same, when the PDF has a real space char there (justified text)
WORD_GAP_EM = 0.18  # gap that inserts a space when the PDF has none
PARA_GAP_EM = 0.55  # vertical gap between lines that still belongs to one paragraph
GUTTER_MIN = 5.0  # minimum width of a column gutter, in points
RULE_MAX = 2.5  # max thickness of a path to count as a table rule
EDGE_ZONE = 0.09  # top/bottom share of the page where headers/footers live
TEXT_LIKE_CHARS = 15  # median span length that makes a column "prose" (vs table column)
_PUA_START, _PUA_END = chr(0xE000), chr(0xF8FF)  # glyphs without a real Unicode value

_ENUM = re.compile(
    r"^(\(?(\d{1,3}(\.\d{1,3})*|[a-zA-Z]|[ivxlcdmIVXLCDM]{1,5})[.)]|\(\d{1,3}\)|\([a-z]\))(?=\s|$)"
)
_NUMBERED_HEADING = re.compile(r"^(\d{1,2}(\.\d{1,2}){0,4})\.?\s+\S")
_CAPTION = re.compile(
    r"^(fig(ura|ure)?|tab(ela|le)?|quadro|gr[aá]fico|chart|imagem|image|"
    r"equa[cç][aã]o|equation|listing|algoritmo|algorithm|esquema|diagrama|diagram)"
    r"\.?\s*(\d+(\.\d+)?|[ivxlc]+)\s*([.:\-–—|]|\s|$)",
    re.IGNORECASE,
)
# Without a figure/table next to it, only "Figura 3: ..." / "Tabela 2 - ..." count.
_STRICT_CAPTION = re.compile(
    _CAPTION.pattern.replace(r"([.:\-–—|]|\s|$)", r"[.:\-–—|]"), re.IGNORECASE
)
_KEY_VALUE = re.compile(r"^[^:]{2,40}:\s+\S")
_EQ_NUMBER = re.compile(r"^\(\s*\d{1,3}(\.\d{1,3})?[a-z]?\s*\)$")
_PAGE_NUMBER = re.compile(
    r"^\s*(?:(?:p[áa]g(?:ina)?|page|p)\.?\s*)?[-–—(\[]?\s*(\d{1,4}|[ivxlcdm]{1,6})\s*[-–—)\]]?"
    r"(?:\s*(?:/|de|of)\s*\d{1,4})?\s*$",
    re.IGNORECASE,
)


